export function ReportsPage() {
  const { user } = useAuth()
  const isAdmin = user?.role === 'admin'
  return <div className="page"><PageHeader title="Reports" subtitle="Download official PDF reports generated by the governance service. Reports open in a new tab — nothing is modified by viewing them." /><Inner isAdmin={isAdmin} /></div>
}

// Split so the header renders even while mines load.
function Inner({ isAdmin }: { isAdmin: boolean }) {
  const mines = useApiResource(() => minesApi.list({ limit: 200 }).then((r) => r.items), [])
  const [busyKey, setBusyKey] = useState<string | null>(null)
  const [msg, setMsg] = useState<{ kind: 'ok' | 'err'; text: string } | null>(null)
  const [mineMap, setMineMap] = useState<Record<string, string>>({})

  const mineList = (mines.data as Mine[] | undefined) ?? []
  const grouped = useMemo(() => ({
    mine: REPORTS.filter((r) => r.param === 'mine'),
    org: REPORTS.filter((r) => r.param === 'org' && (!r.adminOnly || isAdmin)),
  }), [isAdmin])

  async function download(report: ReportSpec, arg: string) {
    const key = report.key + arg
    setBusyKey(key)
    setMsg(null)
    try {
      // Fetch via the authenticated client, then open as a blob URL so the
      // browser's PDF viewer renders it without the token ever entering a URL.
      const token = getStoredToken()
      const url = new URL(`${BASE_URL_RESOLVED}${report.path(arg)}`, window.location.origin)
      const resp = await fetch(url.toString(), {
        headers: token ? { Authorization: `Bearer ${token}` } : {},
      })
      if (!resp.ok) throw new ApiError(resp.status, `Report failed (HTTP ${resp.status})`)
      const blob = await resp.blob()
      if (blob.type !== 'application/pdf') throw new ApiError(0, 'Unexpected response type — not a PDF')
      const blobUrl = URL.createObjectURL(blob)
      window.open(blobUrl, '_blank', 'noopener')
      setTimeout(() => URL.revokeObjectURL(blobUrl), 60_000)
      setMsg({ kind: 'ok', text: `${report.title} generated.` })
    } catch (err) {
      setMsg({ kind: 'err', text: err instanceof ApiError ? err.message : 'Report generation failed.' })
    } finally {
      setBusyKey(null)
    }
  }

  if (mines.loading) return <Skeleton lines={5} />
  if (mines.error) return <ErrorState message={mines.error} onRetry={mines.refetch} />

  return (
    <>
      {msg && <div className={`toast toast-ok${msg.kind === 'err' ? ' toast-danger' : ''}`} role="status">{msg.text}</div>}
      <div className="card">
        <h3>Mine reports</h3>
        <p className="card-sub">Choose a mine, then generate. All mine reports respect the same role and mine scoping as the rest of the system.</p>
        <div className="form-row" style={{ alignItems: 'flex-end' }}>
          <label style={{ minWidth: 220 }}>Mine
            <select value={mineMap.mine ?? ''} onChange={(e) => setMineMap((m) => ({ ...m, mine: e.target.value }))}>
              <option value="">Select mine…</option>
              {mineList.map((m) => <option key={m.id} value={m.id}>{m.name}</option>)}
            </select>
          </label>
        </div>
        {grouped.mine.length === 0
          ? <EmptyState title="No mine reports" message="No mine-scope reports are currently exposed by the backend." />
          : (
            <div className="report-grid">
              {grouped.mine.map((r) => (
                <div key={r.key} className="report-card">
                  <div>
                    <div className="report-title">{r.title}</div>
                    <div className="report-desc">{r.description}</div>
                  </div>
                  <button className="btn btn-primary" disabled={!mineMap.mine || busyKey === r.key + (mineMap.mine ?? '')}
                    onClick={() => download(r, mineMap.mine)}>
                    {busyKey === r.key + (mineMap.mine ?? '') ? 'Generating…' : 'Generate PDF'}
                  </button>
                </div>
              ))}
            </div>
          )}
        {!mineMap.mine && <p className="muted" style={{ fontSize: '.82rem', marginTop: 6 }}>Select a mine above to enable these reports.</p>}
      </div>

      {grouped.org.length > 0 && (
        <div className="card">
          <h3>Organisation reports</h3>
          <p className="card-sub">Organisation-wide reports are restricted to administrators by the backend.</p>
          <div className="report-grid">
            {grouped.org.map((r) => (
              <div key={r.key} className="report-card">
                <div>
                  <div className="report-title">{r.title}{r.adminOnly && <Badge text="ADMIN" tone="info" />} </div>
                  <div className="report-desc">{r.description}</div>
                </div>
                <button className="btn btn-primary" disabled={busyKey === r.key} onClick={() => download(r, mineMap.mine ?? '')}>
                  {busyKey === r.key ? 'Generating…' : 'Generate PDF'}
                </button>
              </div>
            ))}
          </div>
        </div>
      )}
      <div className="card">
        <h3>Inspection reports</h3>
        <p className="card-sub">PDF reports are also available per inspection — see the Inspections page, where each submitted inspection links directly to its report.</p>
        <EmptyState message="Per-inspection PDFs are linked from the inspection list and detail views." />
      </div>      </>
  )
}
