/**
 * Reports — surfaces the PDF report endpoints that already exist on the
 * backend. This page adds NO new functionality: it downloads via the same
 * authenticated client (bearer token) and opens the result in a new tab as a
 * blob URL, because plain <a href> links cannot attach the auth header.
 *
 * Backend reports per section 18 of the UI spec (all existing endpoints):
 *   /api/governance/reports/inspection/{id}.pdf
 *   /api/governance/reports/compliance|safety|violations|telemetry/{mine}.pdf
 *   /api/governance/reports/corrective-actions|emergencies|workforce (admin only)
 *   /api/governance/reports/contractors|audit (admin only)
 */
